#!/usr/bin/env node
// build-word-openers.mjs — carry the CONTRACT's own teaching sentence for
// every declared word into the panel, and name the words that have none.
//
//   node scripts/build-word-openers.mjs           # write
//   node scripts/build-word-openers.mjs --check   # drift gate
//
// WHY. The panel's hover glossary is hand-written (plain-words.ts) and covers
// 21 of the 59 words the contract declares. The spec already carries a
// teaching sentence for 32 of them — the same `opener` the /language/<word>
// rooms render. Nothing was joining the two, so more than half the language
// hovered blank on the surface built to teach it.
//
// THE CURATED PROSE STAYS FIRST. The hand-written lines are in the anyone
// register ("the only tools this run may call"); the spec openers are in the
// spec register ("The CONTROL boundary · {producer-task: predicate}"). Where a
// curated line exists it is the better hover, so this file is a FALLBACK, not
// a replacement — coverage rises 21 → 40 with no loss of voice.
//
// AND THE GAP IS PUBLISHED, not papered over. 19 words have no sentence in
// either source. Writing them here would be inventing language canon, which
// belongs to the spec and its operator, not to a website build script. They
// are listed instead, and the gate lets that list only shrink.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const twin = JSON.parse(readFileSync(`${ROOT}public/ontology/language.json`, 'utf8'))
const words = twin.nodes.filter((n) => String(n.id || '').startsWith('word:'))
if (words.length < 40) {
  console.error(`build-word-openers: only ${words.length} words — refusing`)
  process.exit(2)
}

/* the hover slice · an opener runs to 386 chars at its longest, which is a
   paragraph, not a tooltip. The room shows it whole; the card takes the first
   clause, cut at the spec's own separator and never mid-word. */
const slice = (s) => {
  /* the SENTENCE first — an opener's leading clause often ends at a `·` that
     carries the shape ("The CONTROL boundary · {producer-task: predicate}."),
     so cutting on the separator throws away the definition. Fall back to the
     separator only when the sentence itself is too long for a card. */
  /* a sentence ends at a period followed by a CAPITAL — "e.g." and the "..."
     inside a `${{ … }}` example are not sentence ends, and splitting on a bare
     period cut both mid-thought. */
  const sentence = s.split(/(?<=\.)\s+(?=[A-Z])/)[0].trim().replace(/\s*\([^)]*spec\/[^)]*\)/g, '')
  const short = sentence.length <= 150 ? sentence : sentence.split(' · ')[0].trim()
  if (short.length <= 150) return short
  const cut = short.slice(0, 150)
  return `${cut.slice(0, cut.lastIndexOf(' '))}…`
}

const withOpener = words
  .filter((w) => (w.opener || '').trim())
  .map((w) => [w.title, slice(w.opener)])
  .sort((a, b) => a[0].localeCompare(b[0]))

const curated = new Set(
  (readFileSync(`${ROOT}src/sections/morph/plain-words.ts`, 'utf8')
    .match(/KEY_WORDS[^=]*=\s*\{([\s\S]*?)\n\}/)?.[1] ?? '')
    .split('\n')
    .map((l) => /^\s*([a-z_]+)\s*:/.exec(l)?.[1])
    .filter(Boolean),
)
const VERBS = ['infer', 'exec', 'invoke', 'agent']
const covered = new Set([...curated, ...VERBS, ...withOpener.map(([k]) => k)])
const uncovered = words.map((w) => w.title).filter((t) => !covered.has(t)).sort()

const rows = withOpener.map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')
const body = `// word-openers.generated.ts — AUTO-GENERATED by scripts/build-word-openers.mjs
// from public/ontology/language.json (the served language twin).
// DO NOT EDIT · regenerate: node scripts/build-word-openers.mjs
// Drift gate: src/test/word-openers.test.ts
//
// The contract's own teaching sentence per declared word, sliced to a card.
// FALLBACK ONLY: plain-words.ts stays first where it has a line, because the
// curated prose is in the anyone register and these are in the spec register.

/** word → the contract's opener, first clause, card-length */
export const WORD_OPENER: Record<string, string> = {
${rows}
}

/** declared words with NO teaching sentence in EITHER source. Writing them is
 *  the spec's job, not this build script's — the gate lets this only shrink. */
export const WORDS_WITHOUT_WORDS: string[] = ${JSON.stringify(uncovered)}
`

const OUT = `${ROOT}src/content/word-openers.generated.ts`
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== body) {
    console.error('word-openers: DRIFT · run node scripts/build-word-openers.mjs')
    process.exit(1)
  }
  console.log(`✓ word openers in sync · ${withOpener.length} carried · ${uncovered.length} still wordless`)
} else {
  writeFileSync(OUT, body)
  console.log(`wrote ${withOpener.length} openers · ${uncovered.length} words still have none`)
}
