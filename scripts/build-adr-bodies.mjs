/* ─── build-adr-bodies · the decisions, whole, at the engine pin ─────────────
   The register at /city/decisions carries all 71 decisions as rows. This
   generator gives the SETTLED ones a room of their own: 509 cross-reference
   edges between them had no address to point at, which is the exact case the
   spec chapters were exploded for — you cite the chapter, not the document.

   WHO GETS A ROOM. Everything except `proposed`. A proposal published as an
   indexed page invites citation as though it were settled, and 12 of the 71
   are proposals. They keep their row in the register, with the status said
   out loud and a link to the repo. Accepted, superseded and rejected all get
   rooms — a superseded decision is cited BY its successor, and a rejected one
   is the record of a road not taken, which is what an ADR is for.

   THE PIN, NOT THE CHECKOUT. Every body is read with
   `git show <engine_commit>:docs/adr/<file>` against the sibling engine repo,
   so a moving sibling HEAD can never leak in. No sibling → the committed
   catalog stands and CI never needs one (the build-lessons law).

   Determinism: same pin → byte-identical output. Every body carries its own
   sha256 (a copy is re-provable, never trusted).

   Run:   node scripts/build-adr-bodies.mjs
   Check: node scripts/build-adr-bodies.mjs --check   (exit 5 on drift) */
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { lex } from './lib/md-tokens.mjs'
import { ROOMED } from './lib/adr-law.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const INDEX = join(ROOT, 'public', 'engine', 'adr', 'index.json')
const CATALOG = join(ROOT, 'public', 'engine', 'adr', 'bodies.json')
const OUT = join(ROOT, 'src', 'content', 'adr-bodies.generated.ts')
const PIN = JSON.parse(readFileSync(join(ROOT, '.github/nika-engine-pin.json'), 'utf8'))
const ENGINE_ROOT = process.env.NIKA_ENGINE_ROOT ?? join(ROOT, '..', 'engine', 'repo')

const sha256 = (s) => createHash('sha256').update(s).digest('hex')
const byCp = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

function bodiesAtPin() {
  if (!existsSync(join(ENGINE_ROOT, '.git'))) return null
  const git = (...args) =>
    execFileSync('git', ['-C', ENGINE_ROOT, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  // the pin must be REACHABLE — a shallow or stale clone is not a source
  try {
    git('cat-file', '-e', PIN.engine_commit)
  } catch {
    return null
  }
  const index = JSON.parse(readFileSync(INDEX, 'utf8'))
  return index.adrs
    .filter((a) => ROOMED(a.status))
    .sort((a, b) => byCp(a.id, b.id))
    .map((a) => {
      const raw = git('show', `${PIN.engine_commit}:docs/adr/${a.filename}`)
      /* the frontmatter is metadata the index already carries · the room
         renders the DOCUMENT, so the fence comes off before the lexer */
      const body = raw.replace(/^---\n[\s\S]*?\n---\n/, '')
      const tokens = lex(body, a.filename)
      return {
        id: a.id,
        file: a.filename,
        /* every ## heading · the citable anchors inside the decision */
        sections: tokens
          .filter((t) => t.k === 'h' && t.depth === 2)
          .map((t) => ({ title: t.text, anchor: t.id })),
        words: body.split(/\s+/).filter(Boolean).length,
        sha256: sha256(raw),
        tokens,
      }
    })
}

const render = (bodies) =>
  JSON.stringify(
    {
      adr_bodies_format: 1,
      engine_commit: PIN.engine_commit,
      release_tag: PIN.release_tag,
      law: 'roomed = every status except `proposed` — a proposal published as an indexed page invites citation as though it were settled',
      bodies,
    },
    null,
    2,
  ) + '\n'

function project(catalog) {
  const meta = catalog.bodies.map(({ tokens, ...rest }) => rest)
  const entries = catalog.bodies
    .map((b) => `  ${JSON.stringify(b.id)}: ${JSON.stringify(b.tokens)},`)
    .join('\n')
  return `// adr-bodies.generated.ts — AUTO-GENERATED by scripts/build-adr-bodies.mjs
// from the engine's docs/adr/*.md AT THE PIN (${PIN.release_tag} · ${PIN.engine_commit.slice(0, 12)}),
// read with \`git show <pin>:docs/adr/<file>\` — never from a moving checkout.
// HEAVY (one whole decision per entry): src/** reaches it ONLY through
// src/lib/adr-bodies-access.ts (the register-diet law).
// DO NOT EDIT · regenerate: node scripts/build-adr-bodies.mjs
// Drift gate: node scripts/build-adr-bodies.mjs --check (exit 5) — pnpm check.
import type { BlogToken } from './blog.generated'

/** one decision's shape · the prose rides ADR_TOKENS below */
export interface AdrBody {
  id: string
  file: string
  /** every ## heading · the citable anchors inside the decision */
  sections: { title: string; anchor: string }[]
  words: number
  sha256: string
}

/** the engine release these bodies were read at */
export const ADR_BODIES_PIN = ${JSON.stringify(
    { release_tag: catalog.release_tag, engine_commit: catalog.engine_commit },
    null,
    1,
  )} as const

/** the roomed decisions, in decision order */
export const ADR_BODIES: AdrBody[] = ${JSON.stringify(meta, null, 1)}

/** the prose · one entry per roomed decision */
export const ADR_TOKENS: Record<string, BlogToken[]> = {
${entries}
}
`
}

const check = process.argv.includes('--check')
const fresh = bodiesAtPin()

if (!fresh) {
  if (!existsSync(CATALOG)) {
    console.error('✗ no engine checkout at the pin AND no committed bodies catalog — nothing to derive from')
    process.exit(5)
  }
  console.log('○ adr bodies · no reachable engine checkout at the pin · the committed catalog stands')
  if (!check) writeFileSync(OUT, project(JSON.parse(readFileSync(CATALOG, 'utf8'))))
  process.exit(0)
}

const catalogText = render(fresh)
const projected = project(JSON.parse(catalogText))

if (check) {
  const drift = []
  if (!existsSync(CATALOG) || readFileSync(CATALOG, 'utf8') !== catalogText) drift.push('public/engine/adr/bodies.json')
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== projected) drift.push('src/content/adr-bodies.generated.ts')
  if (drift.length) {
    console.error(`✗ adr bodies drift · run node scripts/build-adr-bodies.mjs\n  ${drift.join('\n  ')}`)
    process.exit(5)
  }
  console.log(`✓ adr bodies in sync with the engine pin (${PIN.release_tag}) · ${fresh.length} rooms`)
  process.exit(0)
}

mkdirSync(dirname(CATALOG), { recursive: true })
writeFileSync(CATALOG, catalogText)
writeFileSync(OUT, projected)
console.log(`wrote ${fresh.length} decision bodies at ${PIN.release_tag}`)
