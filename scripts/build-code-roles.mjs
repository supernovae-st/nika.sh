#!/usr/bin/env node
// build-code-roles.mjs — derive each declared word's SEMANTIC ROLE from the
// served language twin, and emit the compact table the highlighter reads.
//
//   node scripts/build-code-roles.mjs          # write
//   node scripts/build-code-roles.mjs --check  # drift gate (CI)
//
// WHY THIS EXISTS. A generic YAML highlighter colours by SYNTAX class (key,
// string, number) because it does not know the language. Nika is a closed
// contract: the spec declares, for every word, the scopes it may legally
// appear in. So the site can colour by MEANING instead — `command` belongs to
// exec because it cannot live anywhere else, and that is information rather
// than decoration.
//
// THE SOURCE IS THE TWIN, never a hand list: public/ontology/language.json is
// the projection of the spec's own declarations. When this design is promoted
// into design/tokens.yaml, the derivation below moves to the spec's projector
// and the consumers keep reading the same shape — that is the whole point of
// deriving it rather than authoring it.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const TWIN = `${ROOT}public/ontology/language.json`
const OUT = `${ROOT}src/content/code-roles.generated.ts`

const twin = JSON.parse(readFileSync(TWIN, 'utf8'))
const words = twin.nodes.filter((n) => String(n.id || '').startsWith('word:'))
if (words.length < 40) {
  console.error(`build-code-roles: only ${words.length} words in the twin — refusing`)
  process.exit(2)
}

const scopesOf = (w) => new Set((w.meta && w.meta.scopes) || [])

/* the failure grammar · a word whose ONLY homes are the recovery scopes.
   on_error / on_finally / retry are themselves task-scoped heads, so they are
   named explicitly; everything under them derives. */
const RECOVERY = new Set(['on_error', 'on_finally', 'retry'])
const FAIL_HEADS = ['on_error', 'on_finally', 'retry', 'recover']

const fail = new Set(FAIL_HEADS)
for (const w of words) {
  const sc = scopesOf(w)
  if (sc.size && [...sc].every((s) => RECOVERY.has(s))) fail.add(w.title)
}

/* the wiring · the keys that DECLARE an edge. `with` binds data (the binding
   IS the edge), `after` orders without data. They share the ref ink because
   they are the same fact as the ${{ }} they introduce. */
const wire = new Set(['with', 'after'])

/* the boundary · the two declarations that bound what a plan may touch. Their
   descendants inherit by SCOPE at tokenize time (the parent chain), not here:
   `tools` is agent-scoped under a verb and boundary-scoped under permits, and
   only position can tell them apart. */
const boundary = new Set(['permits', 'secrets'])

const declared = new Set(words.map((w) => w.title))
for (const s of [...fail, ...wire, ...boundary]) {
  if (!declared.has(s)) {
    console.error(`build-code-roles: '${s}' is not a declared word — the twin moved`)
    process.exit(2)
  }
}

const list = (s) => [...s].sort().join(' ')
const body = `// code-roles.generated.ts — AUTO-GENERATED by scripts/build-code-roles.mjs
// from public/ontology/language.json (the served language twin).
// DO NOT EDIT · regenerate: node scripts/build-code-roles.mjs
// Drift gate: src/test/code-roles.test.ts re-derives and byte-diffs.
//
// Space-joined strings, not arrays: this table rides the initial bundle and a
// string costs a fraction of a literal array. Parsed once, at module load.

/** the two declarations that bound what a plan may touch */
export const BOUNDARY_WORDS = '${list(boundary)}'.split(' ')
/** the keys that declare an edge — they share the \${{ }} ref ink */
export const WIRE_WORDS = '${list(wire)}'.split(' ')
/** the declared failure grammar */
export const FAIL_WORDS = '${list(fail)}'.split(' ')
/** every word the contract declares (the totality gate reads this) */
export const DECLARED_COUNT = ${words.length}
`

if (process.argv.includes('--check')) {
  const have = readFileSync(OUT, 'utf8')
  if (have !== body) {
    console.error('code-roles: DRIFT · run node scripts/build-code-roles.mjs')
    process.exit(1)
  }
  console.log(`✓ code roles in sync · ${boundary.size} boundary · ${wire.size} wire · ${fail.size} fail`)
} else {
  writeFileSync(OUT, body)
  console.log(`wrote code-roles.generated.ts · ${boundary.size} boundary · ${wire.size} wire · ${fail.size} fail`)
}
