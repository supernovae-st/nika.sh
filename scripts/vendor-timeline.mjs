/* ─── vendor-timeline · the one verifiable record, vendored ──────────────────
   The spec repo's timeline/timeline.yaml is the SSOT of the project's
   history (eras · dated entries · forward gates that carry conditions,
   never dates) — every provable claim re-proven by the spec's own CI
   (timeline/verify.py). This script projects it into a typed module;
   the /timeline page renders the projection, never local prose.

   Run: node scripts/vendor-timeline.mjs
   Default read: the PINNED spec commit via `git show` against the sibling
   checkout, so a moving sibling HEAD can never leak into the projection.
   NIKA_SPEC_ROOT stays the EXPLICIT live-read override: pointing it at a
   checkout is a deliberate act (pre-release rehearsal), never the default.
   Neither reachable: die loudly (the projection must never go stale in
   silence). */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

/* ── pin-read resolution (the build-templates pin-read discipline · 2026-08-03) ──
   readFileSync against the LIVING sibling let an unreleased spec HEAD silently
   re-vendor committed projections on the monorepo machine; the default reader
   now takes the bytes AT the pin, and only an explicit env var reads live. */
const SPEC_PIN = JSON.parse(readFileSync(join(ROOT, '.github/nika-spec-pin.json'), 'utf8'))
const liveRoot = process.env.NIKA_SPEC_ROOT
const siblingGitRoot = [join(ROOT, '..', 'spec', 'repo'), join(ROOT, '..', '..', 'spec', 'repo')].find(
  (p) => {
    if (!existsSync(join(p, '.git'))) return false
    try {
      execFileSync('git', ['-C', p, 'cat-file', '-e', SPEC_PIN.spec_commit], { stdio: 'ignore' })
      return true
    } catch {
      return false
    }
  },
)
/* the ONE reader: NIKA_SPEC_ROOT (explicit) reads the live tree; the sibling
   default reads the PINNED bytes via git show · a moving HEAD cannot leak */
const readSpec = liveRoot
  ? (rel) => readFileSync(join(liveRoot, rel), 'utf8')
  : (rel) =>
      execFileSync('git', ['-C', siblingGitRoot, 'show', `${SPEC_PIN.spec_commit}:${rel}`], {
        encoding: 'utf8',
        maxBuffer: 16 * 1024 * 1024,
      })
const specReachable = liveRoot
  ? existsSync(join(liveRoot, 'timeline/timeline.yaml'))
  : Boolean(siblingGitRoot)
if (!specReachable) {
  console.error(
    'vendor-timeline: no readable spec · neither a sibling carrying the pinned commit nor a usable NIKA_SPEC_ROOT · cannot read timeline/timeline.yaml',
  )
  process.exit(1)
}

const doc = parse(readSpec('timeline/timeline.yaml'))

/* evidence → a public proof href (null for labeled-unprovable classes) */
function proofHref(ev) {
  if (!ev) return null
  switch (ev.class) {
    case 'crates-io':
      return `https://crates.io/crates/${ev.crate}/versions`
    case 'github-release':
      return `https://github.com/${ev.repo}/releases/tag/${ev.tag}`
    case 'github-commit':
      return ev.sha ? `https://github.com/${ev.repo}/commit/${ev.sha}` : null
    case 'github-pr':
      return `https://github.com/${ev.repo}/pull/${ev.pr}`
    case 'scorecard':
      return `https://scorecard.dev/viewer/?uri=${ev.repo}`
    default:
      return null
  }
}

const PROVABLE = new Set(['git-tag', 'github-release', 'github-commit', 'github-pr', 'crates-io'])

const shape = (e) => ({
  date: String(e.date ?? ''),
  precision: e.precision ?? 'day',
  type: e.type ?? 'milestone',
  version: e.version ?? null,
  title: e.title ?? (e.version ? `${e.version}` : ''),
  detail: e.detail ?? null,
  component: e.component ?? null,
  evidence: {
    class: e.evidence?.class ?? 'testimony',
    provable: PROVABLE.has(e.evidence?.class),
    href: proofHref(e.evidence),
    note: e.evidence?.note ?? null,
  },
})

const out = {
  lastUpdated: doc.last_updated,
  eras: doc.eras.map((era) => ({
    id: era.id,
    span: era.span,
    title: era.title,
    story: era.story,
    evidenceClass: era.evidence?.class ?? 'testimony',
    entries: doc.entries.filter((e) => (e.era ? e.era === era.id : inEra(era.id, e.date))).map(shape),
  })),
  gates: doc.gates.map((g) => ({ id: g.id, title: g.title, conditions: g.conditions, note: g.note ?? null })),
}

function inEra(id, date) {
  const d = String(date)
  if (id === 'exploration') return d < '2026-01-01'
  if (id === 'brouillon') return d >= '2026-01-01' && d <= '2026-04-13'
  return d > '2026-04-13'
}

/* the genesis day 2026-04-13 holds BOTH the brouillon close (v0.79.3)
   and the Diamond genesis — the SSOT orders them so the era buckets
   split cleanly: <= 04-13 is the draft closing, > 04-13 is the rewrite,
   and the two 04-13 rewrite entries carry component/type that read as
   diamond in prose regardless of the date bucket */

const banner = `/* GENERATED by scripts/vendor-timeline.mjs — DO NOT EDIT.
   Source of truth: nika-spec timeline/timeline.yaml (verified by the
   spec's own CI · timeline/verify.py). Regenerate: node scripts/vendor-timeline.mjs */`

writeFileSync(
  join(ROOT, 'src/content/timeline.generated.ts'),
  `${banner}\nexport const TIMELINE = ${JSON.stringify(out, null, 2)} as const\n`,
)
console.log(`✓ wrote src/content/timeline.generated.ts · ${doc.entries.length} entries · ${doc.gates.length} gates`)
