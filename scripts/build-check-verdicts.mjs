#!/usr/bin/env node
// build-check-verdicts.mjs — capture what the ENGINE says about every whole
// workflow this site ships, and bake it beside the file.
//
//   node scripts/build-check-verdicts.mjs           # capture (needs `nika`)
//   node scripts/build-check-verdicts.mjs --check   # drift gate
//
// WHY. The site's whole claim is « audited before a token is spent ». It says
// so in prose on a dozen surfaces and SHOWS it nowhere: the panels render the
// file and nothing about its audit. This closes that — the reader sees the
// verdict the binary itself produces, pinned like every other derived fact
// here, never a hand-written summary.
//
// THE HONESTY LINE, and it is the reason this is not a byte-verbatim capture
// of the engine's own text: some hints are facts about THE FILE (an unbounded
// infer, a schema that admits undeclared keys, an undeclared boundary) and
// some are facts about THE MACHINE CHECK RAN ON. `daily-brief` emits three
// `[inputs]` hints that read "./notes/today.md does not exist HERE" — true on
// a CI runner, false on the author's laptop, and meaningless to a reader on
// the website. Baking those would ship a lie with a receipt attached. Only
// file-intrinsic kinds are captured; the environmental ones are dropped by
// name, and the count we render is recomputed from what survived.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const LIB = `${ROOT}public/library`

/* a hint whose truth depends on the filesystem check ran against, not on the
   file — never baked (see the honesty line above) */
const ENVIRONMENTAL = new Set(['inputs'])

let engine
try {
  engine = execFileSync('nika', ['--version'], { encoding: 'utf8' }).trim().split(/\s+/).pop()
} catch {
  console.error('build-check-verdicts: `nika` is not on PATH — the capture needs the real binary')
  process.exit(2)
}

const rows = []
for (const name of readdirSync(LIB).sort()) {
  if (!name.endsWith('.nika.yaml')) continue
  const path = `${LIB}/${name}`
  let out
  try {
    out = execFileSync('nika', ['check', '--json', path], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
  } catch (e) {
    out = e.stdout || ''
  }
  let d
  try {
    d = JSON.parse(out)
  } catch {
    console.error(`build-check-verdicts: ${name} produced no json — skipped`)
    continue
  }
  const yaml = readFileSync(path, 'utf8')
  const id = /^workflow:\s*\n\s+id:\s*(\S+)/m.exec(yaml)?.[1]
  if (!id) {
    console.error(`build-check-verdicts: ${name} has no workflow id — skipped`)
    continue
  }
  const hints = (d.hints ?? []).filter((h) => !ENVIRONMENTAL.has(h.kind))
  rows.push({
    id,
    t: (d.certificate?.derivation ?? []).length || (d.cost?.tasks ?? []).length,
    w: Array.isArray(d.waves) ? d.waves.length : 0,
    p: (d.permits?.source ?? 'floor') === 'declared' ? 1 : 0,
    u: d.cost?.has_unbounded ? 1 : 0,
    h: hints.length,
    clean: d.clean === true ? 1 : 0,
  })
}

rows.sort((a, b) => a.id.localeCompare(b.id))
const packed = rows.map((r) => `${r.id}:${r.t},${r.w},${r.p},${r.u},${r.h},${r.clean}`).join('|')

const body = `// check-verdicts.generated.ts — AUTO-GENERATED by scripts/build-check-verdicts.mjs
// Captured from the REAL binary: nika ${engine} · nika check --json.
// DO NOT EDIT · re-capture: node scripts/build-check-verdicts.mjs
// Drift gate: src/test/check-verdicts.test.ts (skips where nika is absent).
//
// Environmental hints (kind: inputs) are dropped at capture: they describe the
// filesystem check ran against, not the file, and would read as a claim about
// the reader's machine. The rendered count is what survived.

/** the engine that produced these verdicts — the page states it */
export const VERDICT_ENGINE = '${engine}'

/* packed as id:tasks,waves,permitsDeclared,hasUnbounded,hints,clean — one
   string beats N object literals in the initial chunk */
const PACKED = '${packed}'

export interface CheckVerdict {
  tasks: number
  waves: number
  permitsDeclared: boolean
  unbounded: boolean
  hints: number
  clean: boolean
}

export const CHECK_VERDICTS: Record<string, CheckVerdict> = Object.fromEntries(
  PACKED.split('|').map((row) => {
    const [id, rest] = row.split(':')
    const [t, w, p, u, h, c] = rest.split(',').map(Number)
    return [id, { tasks: t, waves: w, permitsDeclared: !!p, unbounded: !!u, hints: h, clean: !!c }]
  }),
)
`

const OUT = `${ROOT}src/content/check-verdicts.generated.ts`
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== body) {
    console.error('check-verdicts: DRIFT · re-capture with node scripts/build-check-verdicts.mjs')
    process.exit(1)
  }
  console.log(`✓ check verdicts in sync · ${rows.length} workflows · nika ${engine}`)
} else {
  writeFileSync(OUT, body)
  console.log(`captured ${rows.length} verdicts from nika ${engine}`)
}
