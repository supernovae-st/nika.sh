#!/usr/bin/env node
// build-nav-stars.mjs — the constellation's stars, as geometry the nav can fly.
//
//   node scripts/build-nav-stars.mjs           # write
//   node scripts/build-nav-stars.mjs --check   # drift gate (CI)
//
// WHY. The Reference panel's rows are tinted by the LENS LAYER of the page each
// one opens. The rail under them opens /map, which draws that same ontology as
// a constellation — so the rail shows the constellation itself, slowly turning,
// and the menu stops being a list beside a map and becomes a window onto one.
//
// THE STARS ARE NOT INVENTED HERE. They are read out of the compiled drawing
// (src/assets/constellation.generated.svg — the same bytes /map serves) and
// each star's LAYER is recovered by matching its fill against the design tokens
// through render-constellation's own LAYER_HUE map. Move a set to another layer
// and both surfaces move together, because there is one layout and one palette.
//
// The flat radial drawing is lifted into depth at RENDER time, not here: the
// layer index is the z, so the seven layers stand apart in space the way they
// stand apart in the file's life. The geometry stays 2-D and honest.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { LAYER_HUE } from './lens/graph/lib/render-constellation.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const OUT = `${ROOT}src/content/nav-stars.generated.ts`

const svg = readFileSync(`${ROOT}src/assets/constellation.generated.svg`, 'utf8')
const tokensTs = readFileSync(`${ROOT}src/design-tokens.generated.ts`, 'utf8')

/** token name → hex, straight out of the projected module (the palette SSOT) */
const tokenHex = (name) => tokensTs.match(new RegExp(`\\b${name}: '(#[0-9a-fA-F]{6})'`))?.[1] ?? null

/* the seven layers, in the file's own order (what you write → what it proves) */
const LAYERS = ['shape', 'flow', 'acts', 'reach', 'boundary', 'refusals', 'proof']
const byHex = new Map()
for (const [layer, token] of Object.entries(LAYER_HUE)) {
  const hex = tokenHex(token)
  if (!hex) {
    console.error(`build-nav-stars: no token value for ${layer} → ${token}`)
    process.exit(2)
  }
  byHex.set(hex.toLowerCase(), LAYERS.indexOf(layer))
}

const box = svg.match(/viewBox="0 0 (\d+) (\d+)"/)
if (!box) {
  console.error('build-nav-stars: the drawing has no viewBox — refusing')
  process.exit(2)
}
const W = Number(box[1])
const H = Number(box[2])

/* the member stars only: every <circle> the drawing fills with a layer hue */
const stars = []
for (const m of svg.matchAll(/<circle[^>]*>/g)) {
  const tag = m[0]
  const cx = Number(tag.match(/\bcx="([\d.]+)"/)?.[1])
  const cy = Number(tag.match(/\bcy="([\d.]+)"/)?.[1])
  const fill = tag.match(/\bfill="(#[0-9a-fA-F]{6})"/)?.[1]?.toLowerCase()
  if (!Number.isFinite(cx) || !Number.isFinite(cy) || !fill) continue
  const layer = byHex.get(fill)
  if (layer == null || layer < 0) continue
  /* centred on the origin, in a unit box — the renderer scales, never the data */
  stars.push([
    Math.round(((cx / W) * 2 - 1) * 1000) / 1000,
    Math.round(((cy / H) * 2 - 1) * 1000) / 1000,
    layer,
  ])
}

if (stars.length < 120) {
  console.error(`build-nav-stars: only ${stars.length} stars recovered — refusing`)
  process.exit(2)
}

const body = `// nav-stars.generated.ts — AUTO-GENERATED by scripts/build-nav-stars.mjs
// from src/assets/constellation.generated.svg (the drawing /map serves) +
// src/design-tokens.generated.ts (the palette SSOT).
// DO NOT EDIT · regenerate: node scripts/build-nav-stars.mjs
// Drift gate: src/test/nav-stars.test.ts re-derives and byte-diffs.
//
// The Reference rail flies these: the site's own constellation, the same stars
// /map draws, lifted into depth by their LAYER at render time. A lazy chunk —
// the entry pays a boundary, never the geometry.

/** the seven layers, in the file's own order · the index is the star's depth */
export const STAR_LAYERS = ${JSON.stringify(LAYERS)} as const

/** [x, y, layer] per star · x and y centred on the origin in a unit box */
export const NAV_STARS: readonly (readonly [number, number, number])[] = ${JSON.stringify(stars)}
`

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== body) {
    console.error('nav-stars: DRIFT · run node scripts/build-nav-stars.mjs')
    process.exit(1)
  }
  console.log(`✓ nav stars in sync · ${stars.length} stars · ${LAYERS.length} layers`)
} else {
  writeFileSync(OUT, body)
  console.log(`wrote nav stars · ${stars.length} stars · ${LAYERS.length} layers`)
}
