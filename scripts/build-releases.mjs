/* ─── build-releases · the engine's release record → a typed projection ──────
   The eight-worlds target named world ⑦ and V5 shipped everything around it:
   /changelog stayed the narrative twin, the ADRs found rooms under the
   belvédère, and « every version, its assets, its digests » still had no
   address. This register is that address: one row per PUBLISHED engine
   release, one room per version, each asset with the sha256 digest GitHub
   recorded when the train uploaded it.

   Two stages, one convention (the tools pipeline's exact shape):

     1 · RECORD → public/releases/catalog.json — `--vendor` asks the public
         GitHub releases record through `gh api` and rewrites the vendored
         catalog. A DELIBERATE dev-machine act (the train cadence), never
         probed at build: CI and offline builds read the committed bytes.
     2 · catalog.json → src/content/releases.generated.ts — the compiled
         typed projection the /releases pages read (generated-module
         convention: adrs.generated · tools.generated). RELEASE_TAGS rides
         along for site.config's RELEASE_PATHS and the lens discovery
         (second-producer law: deriveReleasePaths re-reads THIS module).

   Determinism: same catalog → byte-identical output (releases sorted by
   published date DESCENDING then tag codepoint, assets in upload order, no
   build stamps). The vitest drift gate (releases.test.ts) recompiles and
   diffs, and pins the newest room against the ship log's catch-up ratchet.

   Run:    node scripts/build-releases.mjs            (project from committed)
   Vendor: node scripts/build-releases.mjs --vendor   (gh api → catalog, then project)
   Check:  node scripts/build-releases.mjs --check    (exit 5 on drift) */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG = join(ROOT, 'public', 'releases', 'catalog.json')
const OUT = join(ROOT, 'src', 'content', 'releases.generated.ts')
const REPO = 'supernovae-st/nika'

/** codepoint order · never localeCompare (ICU varies per machine) */
const byCp = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

function vendor() {
  /* the whole public record, one page is enough for years (100 max) — drafts
     and prereleases never enter the register: the register lists what a
     stranger can install, nothing else. */
  const raw = JSON.parse(
    execFileSync(
      'gh',
      ['api', `repos/${REPO}/releases?per_page=100`, '--paginate'],
      { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
    ),
  )
  const releases = raw
    .filter((r) => !r.draft && !r.prerelease && /^v\d+\.\d+\.\d+$/.test(r.tag_name))
    .map((r) => ({
      tag: r.tag_name,
      name: r.name ?? r.tag_name,
      /* day-true: the record's own publish timestamp, date part */
      date: (r.published_at ?? r.created_at).slice(0, 10),
      url: r.html_url,
      assets: (r.assets ?? []).map((a) => ({
        name: a.name,
        size: a.size,
        /* GitHub records the upload digest since 2025 · absent stays absent —
           never fabricate a hash (SHA256SUMS rides the assets for the rest) */
        ...(a.digest ? { sha256: a.digest.replace(/^sha256:/, '') } : {}),
      })),
    }))
    .sort((a, b) => (a.date === b.date ? byCp(b.tag, a.tag) : byCp(b.date, a.date)))
  const doc = {
    releases_format: 1,
    source: `gh api repos/${REPO}/releases (published, non-draft, non-prerelease)`,
    repository: REPO,
    count: releases.length,
    releases,
  }
  writeFileSync(CATALOG, JSON.stringify(doc, null, 1) + '\n')
  console.log(`vendored public/releases/catalog.json (${releases.length} releases)`)
}

function project() {
  const doc = JSON.parse(readFileSync(CATALOG, 'utf8'))
  const rows = doc.releases
  const tags = rows.map((r) => r.tag)
  return `// releases.generated.ts — AUTO-GENERATED by scripts/build-releases.mjs
// from public/releases/catalog.json (vendored DELIBERATELY from the public
// GitHub releases record · never probed at build).
// DO NOT EDIT · regenerate: node scripts/build-releases.mjs
// Re-vendor (dev machine, train cadence): node scripts/build-releases.mjs --vendor
// Drift gate: src/test/releases.test.ts recompiles and byte-diffs.

export interface ReleaseAsset {
  name: string
  size: number
  /** the digest GitHub recorded at upload · absent when the record has none */
  sha256?: string
}

export interface EngineRelease {
  tag: string
  name: string
  /** day-true · the record's own publish date */
  date: string
  url: string
  assets: ReleaseAsset[]
}

/** newest-first · published, non-draft, non-prerelease only */
export const RELEASES: EngineRelease[] = ${JSON.stringify(rows, null, 2)}

/** the room slugs · one per published release (second-producer law: the lens
 * discovery re-derives these from this module, never from site.config) */
export const RELEASE_TAGS: string[] = ${JSON.stringify(tags, null, 2)}
`
}

const mode = process.argv[2]
if (mode === '--vendor') {
  vendor()
  writeFileSync(OUT, project())
  console.log(`wrote src/content/releases.generated.ts (${JSON.parse(readFileSync(CATALOG, 'utf8')).count} releases)`)
} else if (mode === '--check') {
  if (!existsSync(CATALOG)) {
    console.error('✗ public/releases/catalog.json missing — run node scripts/build-releases.mjs --vendor')
    process.exit(5)
  }
  const want = project()
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (want !== have) {
    console.error('✗ releases projection drift: src/content/releases.generated.ts — run node scripts/build-releases.mjs')
    process.exit(5)
  }
  console.log(`✓ releases projection in sync (${JSON.parse(readFileSync(CATALOG, 'utf8')).count} releases)`)
} else {
  writeFileSync(OUT, project())
  console.log(`wrote src/content/releases.generated.ts (${JSON.parse(readFileSync(CATALOG, 'utf8')).count} releases)`)
}
