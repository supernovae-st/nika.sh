import { readFileSync, readdirSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

/* ── le sol · une source, et la question « atteint-elle toutes les surfaces » ─
   Le générateur vivait dans CE dépôt, donc il atteignait le site et son banc,
   et pas le canvas VS Code — un autre dépôt. Une source qui n'atteint pas une
   surface n'est pas la source de vérité de cette surface : c'est la source des
   surfaces qui parlent par hasard le même langage.

   Il est projeté maintenant (nika-spec · design-projector · render_ground_css)
   vers src/styles/ground.generated.css ici et vers src/webview/ dans le
   canvas. Ce gate vérifie trois choses, et la troisième est celle qu'on
   oubliait : qu'une surface le CONSOMME vraiment. Une copie parfaite que
   personne n'applique, c'est zéro surface. */

const ROOT = join(__dirname, '../..')
const GROUND = join(ROOT, 'src/styles/ground.generated.css')

describe('le sol · une source, et des surfaces qui la consomment', () => {
  const css = readFileSync(GROUND, 'utf8')

  it('le fichier est PROJETÉ, jamais écrit ici', () => {
    expect(css.slice(0, 200), 'l’en-tête de projection a disparu — quelqu’un l’a réécrit à la main')
      .toContain('AUTO-GENERATED by nika-spec design-projector')
    expect(existsSync(join(ROOT, 'design/build-ground.mjs')),
      'un générateur local est revenu · le sol ne se produit plus ici, il se reçoit').toBe(false)
  })

  it('le site le charge ET une page l’applique', () => {
    expect(readFileSync(join(ROOT, 'src/index.css'), 'utf8')).toContain('ground.generated.css')
    /* la clause qu’on oubliait : un fichier chargé que rien n’applique ne
       dessine rien. On compte les consommateurs, pas les imports. */
    const consumers = ['src/pages', 'src/sections', 'src/components', 'src/shell']
      .flatMap((d) => walk(join(ROOT, d)))
      .filter((f) => readFileSync(f, 'utf8').includes('nk-ground'))
    expect(consumers.length, 'aucune surface du site n’applique .nk-ground').toBeGreaterThan(0)
  })

  it('le banc inline exactement ce fichier', () => {
    const bench = readFileSync(join(ROOT, 'design/bench.html'), 'utf8')
    expect(bench.includes(css.trim()),
      'le banc et le site ne partagent plus le même sol — relancer node design/bench.mjs').toBe(true)
  })

  it('chaque quantité vient de la projection, pas d’un nombre retapé', () => {
    const tokens = readFileSync(join(ROOT, 'src/design-tokens.generated.ts'), 'utf8')
    const lit = tokens.match(/export const NIKA_MATERIAL = (\{.*\}) as const/)?.[1]
    const mat = JSON.parse(
      (lit as string).replace(/([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:/g, '$1"$2":').replace(/'/g, '"'),
    )
    const g = mat.ground
    expect(css).toContain(`background-size: ${g.grid.cell_px}px ${g.grid.cell_px}px`)
    expect(css).toContain(`${g.spot.radius_px}px circle`)
    expect(css).toContain(`rgb(${g.spot.hue} / ${g.spot.alpha})`)
    /* le curseur est dessiné depuis ses quantités · une data-URI recopiée
       dériverait en silence */
    expect(css, 'le curseur n’est plus dessiné').toContain('cursor: url("data:image/svg+xml,')
    expect(css, 'le point chaud n’est plus le centre de sa boîte')
      .toContain(`") ${g.cursor.box_px / 2} ${g.cursor.box_px / 2}, grab`)
  })

  it('la profondeur sort en contraste forcé, le curseur revient au natif', () => {
    const forced = css.slice(css.indexOf('forced-colors'))
    expect(forced).toContain('background-image: none')
    expect(forced).toContain('cursor: grab')
    expect(forced).toContain('display: none')
  })
})

function walk(dir: string): string[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name))
      : /\.(tsx?|css)$/.test(e.name) ? [join(dir, e.name)] : [])
}
